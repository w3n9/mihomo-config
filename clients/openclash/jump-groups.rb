# 此表达式由构建脚本压成单行，交给 OpenClash 的 ruby_edit 执行。
# 名称与策略都来自 YAML，避免将订阅内容作为 Ruby 代码解释。
(Value["proxy-groups"] || []).reverse.uniq { |group| group["name"] }.reverse.then do |groups|;
  blocked = Value.delete("__overlay-group-names") || [];
  providers = Value["proxy-providers"] || {};
  local_nodes = (providers["local-proxies"] || {})["payload"] || [];
  blocked = blocked + local_nodes.map { |node| node["name"] };
  graph = {};
  matches = lambda do |name, pattern, uncertain|;
    begin;
      !pattern.empty? && name.match?(pattern);
    rescue;
      uncertain;
    end;
  end;
  selected = lambda do |node, settings|;
    name = node["name"].to_s;
    filter = settings["filter"].to_s;
    excluded = settings["exclude-filter"].to_s;
    (filter.empty? || matches.call(name, filter, true)) && !matches.call(name, excluded, false) && !settings["exclude-type"].to_s.split("|").include?(node["type"]);
  end;
  (Value["proxies"] || []).each do |node|;
    graph[node["name"]] = [node["dialer-proxy"]].compact;
  end;
  providers.each_value do |provider|;
    override = provider["override"] || {};
    (provider["payload"] || []).each do |node|;
      graph[node["name"]] = [override["dialer-proxy"] || node["dialer-proxy"]].compact;
    end;
  end;
  groups.each do |group|;
    references = (group["proxies"] || []).dup;
    references += [group["dialer-proxy"], group["empty-fallback"]].compact;
    if group["include-all"] || group["include-all-proxies"];
      references += (Value["proxies"] || []).select { |node| selected.call(node, group) }.map { |node| node["name"] };
    end;
    uses = (group["use"] || []).dup;
    uses += providers.keys if group["include-all"] || group["include-all-providers"];
    uses.uniq.each do |name|;
      provider = providers[name] || {};
      payload = provider["payload"];
      override = provider["override"] || {};
      if payload.is_a?(Array);
        candidates = payload.select { |node| selected.call(node, provider) && selected.call(node, group) };
        references += candidates.map { |node| node["name"] };
        references += [override["dialer-proxy"]].compact unless candidates.empty?;
      else;
        references += [override["dialer-proxy"]].compact;
      end;
    end;
    graph[group["name"]] = references.uniq;
  end;
  memo = {};
  unsafe = lambda do |name, visiting|;
    if blocked.include?(name) || visiting.include?(name);
      true;
    elsif memo.key?(name);
      memo[name];
    else;
      memo[name] = (graph[name] || []).any? { |reference| unsafe.call(reference, visiting + [name]) };
    end;
  end;
  candidates = groups.reject { |group| blocked.include?(group["name"]) || unsafe.call(group["name"], []) }.map { |group| group["name"] };
  groups.each do |group|;
    if group["name"] == "jump-default";
      if candidates.empty?;
        group.delete("proxies");
      else;
        group["proxies"] = candidates;
      end;
    end;
  end;
  groups;
end
